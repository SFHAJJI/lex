    /// <summary>
    /// <paramref name="value"/> folded: each letter or digit by <see cref="Folds"/> (lowered, without its accents), each
    /// non-spacing mark dropped, and every run of anything else one space between words.
    /// </summary>
    public static string NormalizeTitle(string value)
    {
        ArgumentNullException.ThrowIfNull(value);
        var builder = new StringBuilder(value.Length);
        var pendingSpace = false;
        foreach (var character in value)
        {
            if (CharUnicodeInfo.GetUnicodeCategory(character) == UnicodeCategory.NonSpacingMark)
            {
                continue;
            }

            if (!Folds.TryGetValue(character, out var folded))
            {
                Append(builder, ref pendingSpace, character);
                continue;
            }

            foreach (var part in folded)
            {
                Append(builder, ref pendingSpace, part);
            }
        }
        return builder.ToString();
    }

    private static void Append(StringBuilder builder, ref bool pendingSpace, char character)
    {
        if (char.IsLetterOrDigit(character))
        {
            if (pendingSpace && builder.Length != 0)
            {
                builder.Append(' ');
            }
            builder.Append(character);
            pendingSpace = false;
        }
        else
        {
            pendingSpace = true;
        }
    }

