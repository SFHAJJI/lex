    private static FrozenDictionary<char, string> Parse(string table)
    {
        var folds = new Dictionary<char, string>();
        foreach (var entry in table.Split(' '))
        {
            var parts = entry.Split('>');
            var fold = parts.Length == 2 ? parts[1].Split('+') : [];
            if (parts[0].Length != 4 || fold.Length is < 1 or > 2 || fold.Any(static code => code.Length != 4))
            {
                throw new InvalidOperationException($"The title folding table holds a malformed entry: '{entry}'.");
            }

            folds.Add(Code(parts[0]), string.Concat(fold.Select(static code => Code(code))));
        }
        return folds.ToFrozenDictionary();
    }

    private static char Code(string hex) =>
        (char)ushort.Parse(hex, NumberStyles.AllowHexSpecifier, CultureInfo.InvariantCulture);
