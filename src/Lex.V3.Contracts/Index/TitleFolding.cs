/// <summary>
/// Lex's own title folding: what a Luxembourg index's <c>normalized_title</c> column is written with, and what a title a
/// reader types is folded with before it is matched against that column. A letter or digit is lowered and loses its
/// accents, a non-spacing mark is dropped, and anything else separates words; a run of separators is one space, and none
/// leads or trails.
/// </summary>
/// <remarks>
/// <para>
/// The fold was the operating system's language library's (ICU's): <c>string.Normalize</c> to the canonical
/// decomposition, the non-spacing marks dropped, <c>char.ToLowerInvariant</c>, and <c>Normalize</c> back. The release
/// image carries no such library: .NET runs there globalization-invariant, where <c>Normalize</c> returns its input
/// unchanged, so the server stopped removing the accents from what a reader typed while every index, built on a machine
/// with the library, holds its titles without them. "Congé parental" found nothing on the server (plan 0.8). The table
/// below is that fold, letter by letter: every letter and digit of the Basic Multilingual Plane whose fold is not itself
/// (2,140 of them). The indexes already built are read as they were written, and the fold is the same with the library
/// or without it, because nothing here asks the library.
/// </para>
/// <para>
/// <c>TitleFoldingTests</c> holds the table to the library wherever one is present: every character of the plane folds
/// as the library folded it, and a character that does not is named with the entry the table needs. Three differences
/// are by design: a lone surrogate and U+FFFE, which made the library throw, separate words; a character beyond the plane
/// separates words, as each half of its surrogate pair did, where the library replaced the CJK compatibility ideographs
/// of U+2F800 to U+2FA1D by their unified forms; and a Hangul syllable typed as its separate jamo stays as typed, where
/// the library composed it again. No title Lex holds meets any of the three.
/// </para>
/// </remarks>
