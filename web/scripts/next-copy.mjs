/** The table of an interface language; French for any other (the site's default). */
export function nextCopy(locale) {
  return Object.hasOwn(NEXT_COPY, locale) ? NEXT_COPY[locale] : FR;
}

/** A template filled with the values its places name; a place with no value throws (a sentence is never shown with a hole). */
export function fillNext(template, values = {}) {
  return String(template).replace(/\{([a-zA-Z]+)\}/gu, (place, name) => {
    if (!Object.hasOwn(values, name) || values[name] === null || values[name] === undefined) throw new Error(`no value for ${place} in ${JSON.stringify(template)}`);
    return String(values[name]);
  });
}

/** A whole number with its thousands grouped as the language writes them. */
export function groupedCount(count, locale) {
  const number = Number(count);
  return Number.isFinite(number) ? number.toLocaleString(locale === 'fr' ? 'fr-FR' : 'en-GB') : '';
}

/**
 * The form of a counted entry for `count` (`zero` when the entry has one and the count is 0; `one` for 1, and in French for
 * 0 too; else `other`), filled with the count grouped and the other values.
 */
export function countedForm(entry, count, locale, values = {}) {
  const number = Number(count) || 0;
  const form = number === 0 && typeof entry.zero === 'string' ? entry.zero
    : number === 1 || (number === 0 && locale === 'fr') ? entry.one
      : entry.other;
  return fillNext(form, { ...values, count: groupedCount(number, locale) });
}

/** A calendar date (yyyy-mm-dd, a longer instant too) as dd/mm/yyyy, in both languages; '' when it is not one. */
export function numericDate(iso) {
  const match = /^([0-9]{4})-([0-9]{2})-([0-9]{2})/u.exec(typeof iso === 'string' ? iso : '');
  return match === null ? '' : `${match[3]}/${match[2]}/${match[1]}`;
}

/** A number with decimals as the language writes it (a comma in French), with `digits` decimals when given. */
export function decimal(value, locale, digits = null) {
  const number = Number(value);
  if (!Number.isFinite(number)) return '';
  const text = digits === null ? String(number) : number.toFixed(digits);
  return locale === 'fr' ? text.replace('.', ',') : text;
}

/** A small count as a word with a capital ("Six"), or its digits when the table holds no word for it. */
export function countWord(count, locale) {
  const word = nextCopy(locale).numberWords[count];
  return typeof word === 'string' ? word.charAt(0).toUpperCase() + word.slice(1) : groupedCount(count, locale);
}
